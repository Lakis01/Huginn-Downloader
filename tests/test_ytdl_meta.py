class ParseInfoTests(unittest.TestCase):
    def test_official_art_track_parses_metadata_and_role_credits(self):
        result = parse_info({
            "description": OFFICIAL_DESCRIPTION,
            "title": "Stay (feat. Earth, Wind & Fire)",
            "duration": 240,
        })

        self.assertTrue(result["is_tagged"])
        self.assertEqual(result["title"], "Stay")
        self.assertEqual(result["artist"], "Rihanna feat. Earth, Wind & Fire")
        self.assertEqual(result["artists"], ["Rihanna", "Earth, Wind & Fire"])
        self.assertEqual(result["albumartist"], "Rihanna")
        self.assertEqual(result["album"], "Unapologetic")
        self.assertEqual(result["date"], "2012-11-19")
        self.assertEqual(result["originaldate"], "1979")
        self.assertEqual(result["label"], "Def Jam Recordings")
        self.assertEqual(result["copyright"], "℗ 1979 Def Jam Recordings")
        self.assertEqual(result["distributor"], "Sony")
        self.assertEqual(result["composers"], ["Mikky Ekko", "Justin Parker"])
        self.assertEqual(result["lyricists"], ["Mikky Ekko"])
        self.assertEqual(result["composer"], "Mikky Ekko; Justin Parker")
        self.assertEqual(result["producers"], ["Mikky Ekko"])
        self.assertEqual(result["engineers"], ["Manny Marroquin"])
        self.assertEqual(result["publisher"], "Kobalt Music Publishing")
        self.assertEqual(result["isrc"], "USUM71212345")
        self.assertEqual(result["genre"], "Pop")
        self.assertEqual(result["recordingdate"], "2012")
        self.assertEqual(result["studio"], "Example Studios")
        self.assertEqual(result["duration"], 240)

    def test_art_track_co_credits_are_distinct_and_ampersand_name_is_not_split(self):
        co_credit = parse_info({
            "description": "Provided to YouTube by Example\n"
            "Mountains Falling · David Lynch · John Neff\n"
            "Crazy Clown Time\nAuto-generated by YouTube.",
            "title": "Mountains Falling",
        })
        ampersand_name = parse_info({
            "description": "Provided to YouTube by Example\n"
            "The Sound of Silence · Simon & Garfunkel\n"
            "Wednesday Morning, 3 A.M.\nAuto-generated by YouTube.",
            "title": "The Sound of Silence",
        })

        self.assertEqual(co_credit["artists"], ["David Lynch", "John Neff"])
        self.assertEqual(co_credit["artist"], "David Lynch · John Neff")
        self.assertEqual(ampersand_name["artist"], "Simon & Garfunkel")
        self.assertEqual(ampersand_name["artists"], ["Simon & Garfunkel"])

    def test_art_track_maps_arranger_conductor_performer_engineers_and_instruments(self):
        result = parse_info({
            "description": "Provided to YouTube by Example\n"
            "A Song · The Band\nAn Album\n"
            "Arranger: Jane Doe\n"
            "Conductor: John Doe\n"
            "Associated Performer, Guitar: Alice Example\n"
            "Studio Personnel, Recording Engineer: Bob Example\n"
            "Studio Personnel, Mastering Engineer: Carol Example\n"
            "Auto-generated by YouTube.",
            "title": "A Song",
        })

        self.assertEqual(result["arrangers"], ["Jane Doe"])
        self.assertEqual(result["conductors"], ["John Doe"])
        self.assertEqual(result["performers"], ["Alice Example"])
        self.assertEqual(result["instruments"], ["Guitar"])
        self.assertEqual(
            result["engineers"], ["Bob Example", "Carol Example"]
        )

    def test_art_track_without_album_skips_role_and_publisher_lines(self):
        result = parse_info({
            "description": "Provided to YouTube by Example\n"
            "A Song · The Band\n"
            "Arranger: Jane Doe\n"
            "Associated Performer: Alice Example\n"
            "Music Publisher: Example Publishing\n"
            "Auto-generated by YouTube.",
            "title": "A Song",
        })

        self.assertEqual(result["album"], "")
        self.assertEqual(result["arrangers"], ["Jane Doe"])
        self.assertEqual(result["performers"], ["Alice Example"])
        self.assertEqual(result["publisher"], "Example Publishing")

    def test_legacy_composer_credit_labels_remain_supported(self):
        result = parse_info({
            "description": "Provided to YouTube by Example\n"
            "A Song · The Band\nAn Album\n"
            "Composer Lyricist: First Writer\n"
            "Composer Music: Second Writer\n"
            "Auto-generated by YouTube.",
            "title": "A Song",
        })

        self.assertEqual(result["composers"], ["First Writer", "Second Writer"])
        self.assertEqual(result["lyricists"], ["First Writer"])
        self.assertEqual(result["composer"], "First Writer; Second Writer")

    def test_release_date_precision_and_upload_date_fallback(self):
        may = parse_info({
            "description": "Provided to YouTube by Example\n"
            "Track · Artist\nAlbum\nReleased on: 2020-05\n"
            "Auto-generated by YouTube.",
            "title": "Track",
        })
        copyright_only = parse_info({
            "description": "Provided to YouTube by Example\n"
            "Track · Artist\nAlbum\n℗ 2004 Example Label\n"
            "Auto-generated by YouTube.",
            "title": "Track",
        })
        upload_date = parse_info({"title": "Regular upload", "upload_date": "20240315"})

        self.assertEqual(may["date"], "2020-05")
        self.assertEqual(copyright_only["date"], "2004")
        self.assertEqual(copyright_only["originaldate"], "")
        self.assertEqual(upload_date["date"], "2024-03-15")
        self.assertEqual(upload_date["originaldate"], "")

    def test_fallback_parses_artist_title_and_preserves_full_featuring_phrase(self):
        result = parse_info({
            "title": "Artist A featuring Artist B - My Song (Official Music Video) [4K]",
            "uploader": "Artist A VEVO",
            "upload_date": "20240315",
        })

        self.assertFalse(result["is_tagged"])
        self.assertEqual(result["artist"], "Artist A featuring Artist B")
        self.assertEqual(result["artists"], ["Artist A", "Artist B"])
        self.assertEqual(result["title"], "My Song")
        self.assertEqual(result["date"], "2024-03-15")

    def test_fallback_cleans_channel_and_extracts_title_featuring_credit(self):
        result = parse_info({
            "title": "Cool Track (Lyrics) (feat. Guest)",
            "uploader": "MainActVEVO",
            "channel": "Main Act - Topic",
        })
        suffix_after_feature = parse_info({
            "title": "Cool Track (feat. Guest) (Lyrics)",
            "channel": "Main Act - Topic",
        })

        self.assertEqual(result["artist"], "Main Act feat. Guest")
        self.assertEqual(result["artists"], ["Main Act", "Guest"])
        self.assertEqual(result["title"], "Cool Track")
        self.assertEqual(suffix_after_feature["artist"], "Main Act feat. Guest")
        self.assertEqual(suffix_after_feature["title"], "Cool Track")

    def test_legacy_keys_and_types_are_retained(self):
        result = parse_info({"title": "A title", "duration": 17})

        self.assertTrue({
            "artist", "title", "album", "date", "composer", "is_tagged", "duration",
            "artists", "albumartist", "originaldate", "label", "copyright",
            "distributor", "publisher", "isrc", "genre", "recordingdate", "studio",
            "composers", "lyricists", "producers", "arrangers", "conductors",
            "engineers", "performers", "instruments",
        }.issubset(result))
        self.assertIsInstance(result["artist"], str)
        self.assertIsInstance(result["title"], str)
        self.assertIsInstance(result["album"], str)
        self.assertIsInstance(result["date"], str)
        self.assertIsInstance(result["composer"], str)
        self.assertIsInstance(result["is_tagged"], bool)
        self.assertEqual(result["duration"], 17)


class SanitizeFilenameTests(unittest.TestCase):
    def test_filename_removes_unsafe_characters_and_trailing_dots_or_spaces(self):
        sanitized = sanitize_filename('AC/DC: What\'s "Up"?*')

        self.assertFalse(any(character in sanitized for character in '/\\:*?"<>|'))
        self.assertEqual(sanitized, sanitized.rstrip(". "))
        self.assertEqual(sanitize_filename("name.  "), "name")


def _make_silence_opus(path):
    subprocess.run(
        ["ffmpeg", "-y", "-v", "error", "-f", "lavfi",
         "-i", "sine=frequency=440:duration=1",
         "-c:a", "libopus", path],
        check=True,
    )


def _make_silence_m4a(path):
    subprocess.run(
        ["ffmpeg", "-y", "-v", "error", "-f", "lavfi",
         "-i", "sine=frequency=440:duration=1",
         "-c:a", "aac", path],
        check=True,
    )


def _make_thumbnail(path, size=(1280, 720)):
    from PIL import Image

    Image.new("RGB", size, (200, 30, 30)).save(path, "JPEG")


class TagAudioFileTests(unittest.TestCase):
    def test_opus_tags_are_multivalue_and_artwork_is_cropped_square(self):
        from mutagen.oggopus import OggOpus

        meta = parse_info({
            "description": OFFICIAL_DESCRIPTION,
            "title": "Stay (feat. Earth, Wind & Fire)",
            "duration": 240,
        })
        with tempfile.TemporaryDirectory() as tmp:
            src = os.path.join(tmp, "track.opus")
            thumb = os.path.join(tmp, "thumb.jpg")
            _make_silence_opus(src)
            _make_thumbnail(thumb)
            seed = OggOpus(src)
            seed["description"] = ["seeded description"]
            seed["comment"] = ["seeded comment"]
            seed["webpage_url"] = ["https://example.invalid/seed"]
            seed.save()

            tag_audio_file(src, meta, thumb)

            tagged = OggOpus(src)
            tags = tagged.tags
            self.assertIsInstance(tags["artist"], list)
            self.assertEqual(tags["artist"], ["Rihanna feat. Earth, Wind & Fire"])
            self.assertEqual(tags["artists"], ["Rihanna", "Earth, Wind & Fire"])
            self.assertEqual(tags["album"], ["Unapologetic"])
            self.assertEqual(tags["albumartist"], ["Rihanna"])
            self.assertEqual(tags["date"], ["2012-11-19"])
            self.assertEqual(tags["originaldate"], ["1979"])
            self.assertEqual(tags["composer"], ["Mikky Ekko", "Justin Parker"])
            self.assertEqual(tags["lyricist"], ["Mikky Ekko"])
            self.assertEqual(tags["producer"], ["Mikky Ekko"])
            self.assertEqual(tags["engineer"], ["Manny Marroquin"])
            self.assertIsInstance(tags["label"], list)
            self.assertEqual(tags["label"], ["Def Jam Recordings"])
            lowered = {key.lower() for key in tags.keys()}
            for cleared in ("description", "purl", "synopsis", "comment", "webpage_url"):
                self.assertNotIn(cleared, lowered)

            self.assertIn("metadata_block_picture", tags)
            import base64

            from mutagen.flac import Picture

            picture = Picture(base64.b64decode(tags["metadata_block_picture"][0]))
            self.assertEqual(picture.type, 3)
            self.assertEqual((picture.width, picture.height), (720, 720))

    def test_m4a_tags_standard_atoms_freeform_artists_and_cover(self):
        from mutagen.mp4 import MP4

        meta = parse_info({
            "description": OFFICIAL_DESCRIPTION,
            "title": "Stay (feat. Earth, Wind & Fire)",
            "duration": 240,
        })
        with tempfile.TemporaryDirectory() as tmp:
            src = os.path.join(tmp, "track.m4a")
            thumb = os.path.join(tmp, "thumb.jpg")
            _make_silence_m4a(src)
            _make_thumbnail(thumb)

            tag_audio_file(src, meta, thumb)

            tagged = MP4(src)
            self.assertEqual(tagged["\xa9nam"], ["Stay"])
            self.assertEqual(tagged["\xa9ART"], ["Rihanna feat. Earth, Wind & Fire"])
            self.assertEqual(tagged["\xa9alb"], ["Unapologetic"])
            self.assertEqual(tagged["\xa9day"], ["2012-11-19"])
            freeforms = tagged["----:com.apple.iTunes:ARTISTS"]
            decoded = [bytes(value).decode("utf-8") for value in freeforms]
            self.assertEqual(decoded, ["Rihanna", "Earth, Wind & Fire"])
            self.assertIn("covr", tagged)
            self.assertTrue(len(bytes(tagged["covr"][0])) > 0)

    def test_fallback_single_artist_omits_artists_and_keeps_landscape(self):
        from mutagen.oggopus import OggOpus

        meta = parse_info({"title": "Cool Track", "channel": "Main Act - Topic"})
        self.assertEqual(meta["artists"], ["Main Act"])
        with tempfile.TemporaryDirectory() as tmp:
            src = os.path.join(tmp, "track.opus")
            thumb = os.path.join(tmp, "thumb.jpg")
            _make_silence_opus(src)
            _make_thumbnail(thumb)

            tag_audio_file(src, meta, thumb)

            tagged = OggOpus(src)
            tags = tagged.tags
            lowered = {key.lower() for key in tags.keys()}
            self.assertNotIn("artists", lowered)
            self.assertEqual(tags["artist"], ["Main Act"])
            import base64

            from mutagen.flac import Picture

            picture = Picture(base64.b64decode(tags["metadata_block_picture"][0]))
            self.assertEqual((picture.width, picture.height), (1280, 720))


