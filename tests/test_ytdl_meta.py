def _make_stereo_webm_opus(path, duration=4):
    subprocess.run(
        ["ffmpeg", "-y", "-v", "error", "-f", "lavfi",
         "-i", f"sine=frequency=440:duration={duration}", "-ac", "2",
         "-c:a", "libopus", "-b:a", "128k", "-f", "webm", str(path)],
        check=True,
    )


def _make_muxed_mp4(path, duration=2):
    subprocess.run(
        ["ffmpeg", "-y", "-v", "error", "-f", "lavfi", "-i",
         f"color=c=blue:s=64x64:r=25:d={duration}", "-f", "lavfi", "-i",
         f"sine=frequency=440:duration={duration}", "-map", "0:v:0", "-map", "1:a:0",
         "-c:v", "mpeg4", "-c:a", "aac", "-shortest", str(path)],
        check=True,
    )


def _probe_media(path):
    result = subprocess.run(
        ["ffprobe", "-v", "error", "-show_streams", "-show_format",
         "-of", "json", str(path)],
        capture_output=True, text=True, check=True,
    )
    return json.loads(result.stdout)


def _make_thumbnail(path, size=(1280, 720)):
    from PIL import Image

    Image.new("RGB", size, (200, 30, 30)).save(path, "JPEG")


def _make_webp_thumbnail(path, size=(1280, 720)):
    from PIL import Image

    Image.new("RGB", size, (200, 30, 30)).save(path, "WEBP")


